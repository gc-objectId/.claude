const { chromium } = require("/Users/ryanducharme/dev/orci/qa-suite/node_modules/playwright");
const BASE = "http://localhost:52629";
const [pmrn] = process.argv.slice(2);
(async () => {
  const browser = await chromium.launch({ args: ["--host-resolver-rules=MAP *.sentry.io ~NOTFOUND"] });
  const ctx = await browser.newContext();
  const page = await ctx.newPage();
  const posts = [];
  page.on("request", (r) => { if (r.method() === "POST" && r.url().includes("/operations/create")) posts.push(r.url().replace(BASE, "") + " [X-Tenant-Id=" + (r.headers()["x-tenant-id"] || "-") + "] body=" + r.postData()); });
  page.on("response", async (r) => { if (r.url().includes("/operations/create")) console.log("create response:", r.status(), (await r.text()).slice(0, 120)); });
  await page.goto(BASE + "/login");
  await page.locator("#username").fill("admin");
  await page.locator("#password").evaluate((el, pwd) => { const s = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value").set; s.call(el, pwd); el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true })); }, "admin");
  await page.locator('button[type="submit"]').click();
  await page.waitForURL("**/", { timeout: 10000 });
  const link = page.locator('a.dropdown-item[href="/admin/patients?client_id=demo-demo"]');
  const toggles = page.locator(".launch-row__menu-toggle");
  await toggles.first().waitFor({ timeout: 10000 });
  for (const t of await toggles.all()) { await t.click(); if (await link.isVisible()) { await link.click(); break; } await page.keyboard.press("Escape"); }
  await page.waitForURL(/client_id=demo-demo/);
  await page.getByRole("searchbox", { name: "Search patients" }).fill(pmrn);
  await page.locator("table tbody tr", { hasText: pmrn }).getByRole("button", { name: "View" }).click();
  await page.waitForURL(/admin\/patients\/[0-9a-f-]+/);
  await page.locator("table tbody tr").first().waitFor();
  const before = await page.locator("table tbody tr").count();
  const buttons = await page.getByRole("button").allTextContents();
  console.log("buttons on patient page:", JSON.stringify(buttons.filter((b) => b.trim())));
  const trigger = page.getByRole("button", { name: /operation/i }).first();
  await trigger.click();
  await page.locator(".modal").waitFor({ timeout: 5000 });
  const sel = page.locator('.modal select[name="procedureType"]');
  const options = await sel.locator("option").allTextContents();
  console.log("procedure options (first 5):", JSON.stringify(options.slice(0, 5)));
  await sel.selectOption({ index: 1 });
  await page.locator(".modal").getByRole("button", { name: "Add Operation" }).click();
  await page.waitForTimeout(4000);
  console.log("POST:", posts.join("\n"));
  const after = await page.locator("table tbody tr").count();
  console.log("case rows before/after:", before, after);
  const hrefs = await page.locator("table tbody tr a").evaluateAll((as) => as.map((a) => a.getAttribute("href")));
  console.log("all case links:", JSON.stringify(hrefs));
  await page.screenshot({ path: `${__dirname}/create-op.png`, fullPage: true });
  await browser.close();
})().catch((e) => { console.error("ERR", e); process.exit(1); });
