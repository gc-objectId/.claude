const { chromium } = require("/Users/ryanducharme/dev/orci/qa-suite/node_modules/playwright");
const BASE = "http://localhost:52629";
const S = __dirname;
const [pmrn, caseId, label] = process.argv.slice(2);
(async () => {
  const browser = await chromium.launch({ args: ["--host-resolver-rules=MAP *.sentry.io ~NOTFOUND"] });
  const ctx = await browser.newContext();
  const page = await ctx.newPage();
  const copied = [];
  await page.exposeFunction("recordCopiedText", (t) => copied.push(t));
  await page.addInitScript(`Object.defineProperty(navigator,"clipboard",{configurable:true,value:{writeText:(t)=>window.recordCopiedText(t)}});`);
  const apiCalls = [];
  page.on("request", (r) => { if (r.url().includes("/api/")) apiCalls.push(r.url().replace(BASE, "") + " [X-Tenant-Id=" + (r.headers()["x-tenant-id"] || "-") + "]"); });
  const failed = [];
  page.on("response", (r) => { if (r.url().includes("/api/") && r.status() >= 400) failed.push(r.status() + " " + r.url().replace(BASE, "")); });
  await page.goto(BASE + "/login");
  await page.locator("#username").fill("admin");
  await page.locator("#password").evaluate((el, pwd) => { const s = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value").set; s.call(el, pwd); el.dispatchEvent(new Event("input", { bubbles: true })); el.dispatchEvent(new Event("change", { bubbles: true })); }, "admin");
  await page.locator('button[type="submit"]').click();
  await page.waitForURL("**/", { timeout: 10000 });
  await page.locator(".home-hero").waitFor({ timeout: 10000 });
  console.log("home url:", page.url());
  console.log("bundle:", await page.evaluate(() => [...document.scripts].map((s) => s.src).filter(Boolean).join(",")));
  const link = page.locator('a.dropdown-item[href="/admin/patients?client_id=demo-demo"]');
  const toggles = page.locator(".launch-row__menu-toggle");
  await toggles.first().waitFor({ timeout: 10000 });
  let opened = false;
  for (const t of await toggles.all()) { await t.click(); if (await link.isVisible()) { await link.click(); opened = true; break; } await page.keyboard.press("Escape"); }
  if (!opened) throw new Error("no Patients link for demo-demo on Home");
  await page.waitForURL(/client_id=demo-demo/);
  console.log("patients url:", page.url());
  await page.getByRole("searchbox", { name: "Search patients" }).fill(pmrn);
  const row = page.locator("table tbody tr", { hasText: pmrn });
  await row.getByRole("button", { name: "View" }).click();
  await page.waitForURL(/admin\/patients\/[0-9a-f-]+/);
  console.log("patient url:", page.url());
  const crumb = page.locator(".admin-page__trail").getByRole("link", { name: "Patients" });
  await crumb.waitFor();
  console.log("crumb href:", await crumb.getAttribute("href"));
  const caseRow = page.locator("table tbody tr", { hasText: caseId });
  await caseRow.waitFor();
  const launchHref = await caseRow.getByRole("link", { name: "Launch" }).getAttribute("href");
  const viewOp = caseRow.getByRole("link", { name: "View Operation" });
  console.log("launch href:", launchHref);
  console.log("view operation href:", await viewOp.getAttribute("href"));
  await page.screenshot({ path: `${S}/${label}-patient.png`, fullPage: true });
  await viewOp.click();
  await page.waitForTimeout(4000);
  console.log("debugger url:", page.url());
  console.log("debugger meta:", await page.locator(".admin-page__meta").textContent().catch(() => null));
  console.log("'Unable to load case' count:", await page.getByText("Unable to load case").count());
  await page.screenshot({ path: `${S}/${label}-debugger.png`, fullPage: true });
  await page.getByRole("tab", { name: "Operation", exact: true }).click();
  await page.getByRole("button", { name: "Launch link" }).click({ timeout: 10000 }).catch((e) => console.log("launch link click failed:", e.message.split("\n")[0]));
  await page.waitForTimeout(500);
  console.log("copied launch link:", JSON.stringify(copied));
  const lp = await ctx.newPage();
  const lpFailed = [];
  lp.on("response", (r) => { if (r.url().includes("/api/") && r.status() >= 400) lpFailed.push(r.status() + " " + r.url().replace(BASE, "")); });
  await lp.goto(BASE + launchHref);
  await lp.waitForTimeout(8000);
  console.log("followed Launch -> url:", lp.url());
  console.log("followed Launch -> body:", (await lp.locator("body").innerText()).replace(/\s+/g, " ").slice(0, 300));
  console.log("followed Launch -> failed api:", JSON.stringify(lpFailed));
  await lp.screenshot({ path: `${S}/${label}-launch.png`, fullPage: true });
  console.log("api calls from patient/debugger pages:\n  " + apiCalls.join("\n  "));
  console.log("failed api calls:", JSON.stringify(failed));
  await browser.close();
})().catch((e) => { console.error("ERR", e); process.exit(1); });
